import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

/**
 * Joins apps_script/*.gs (in name order) into one file you can paste into the Sheet's Apps Script editor:
 *   npm run gs:bundle   ->  apps_script/dist/AutoBooker.gs
 * With clasp installed you do not need this: `npm run gs:push` uploads the files as they are.
 */
export const APPS_SCRIPT_DIR = resolve(process.cwd(), "apps_script");

export async function listScriptFiles(dir = APPS_SCRIPT_DIR): Promise<string[]> {
  return (await readdir(dir)).filter((f) => f.endsWith(".gs")).sort().map((f) => resolve(dir, f));
}

export async function bundleAppsScript(dir = APPS_SCRIPT_DIR): Promise<string> {
  const files = await listScriptFiles(dir);
  const parts: string[] = [];
  for (const f of files) {
    const name = f.slice(dir.length + 1);
    parts.push(`// ===== ${name} =====`, (await readFile(f, "utf8")).replace(/\s+$/, ""), "");
  }
  return `// Generated by "npm run gs:bundle" from apps_script/*.gs. Edit the parts, not this file.\n\n${parts.join("\n")}`;
}

if (process.argv[1] && /bundle-apps-script\.(ts|js)$/.test(process.argv[1])) {
  const out = resolve(APPS_SCRIPT_DIR, "dist", "AutoBooker.gs");
  await mkdir(resolve(APPS_SCRIPT_DIR, "dist"), { recursive: true });
  const text = await bundleAppsScript();
  await writeFile(out, text);
  console.log(`${out}  (${text.split("\n").length} lines from ${(await listScriptFiles()).length} files)`);
}
